"""Carga el dataset del prototipo en el esquema (SQLite para la prueba) y lo reconstruye como PropuestaHorario."""
import re, sqlite3, os
from src.models import Sesion, PropuestaHorario, Docente, Aula, Dedicacion, Tecnologia

DIAS = ["Lunes", "Martes", "Miércoles", "Jueves", "Viernes", "Sábado"]


def conectar():
    ddl = open(os.path.join(os.path.dirname(__file__), "schema.sql"), encoding="utf-8").read()
    ddl = re.sub(r"INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY", "INTEGER PRIMARY KEY AUTOINCREMENT", ddl)
    con = sqlite3.connect(":memory:")
    con.execute("PRAGMA foreign_keys = ON")
    con.executescript(ddl)
    return con


def cargar(con, docentes, aulas, propuesta):
    c = con.cursor()
    c.execute("INSERT INTO semestre VALUES (?,?,?)", (propuesta.semestre, "2026-07-20", "2026-11-28"))
    c.execute("INSERT INTO usuario(nombre, correo, rol) VALUES ('Coordinador','coord@ejemplo.edu','COORDINADOR')")
    ded = {d: i + 1 for i, d in enumerate(Dedicacion)}
    from src.models import HORAS_MAXIMAS_POR_DEDICACION as H
    for d, i in ded.items():
        c.execute("INSERT INTO dedicacion VALUES (?,?,?)", (i, d.value, H[d]))
    esp = {}
    for d in docentes:
        if d.especialidad not in esp:
            esp[d.especialidad] = len(esp) + 1
            c.execute("INSERT INTO especialidad VALUES (?,?)", (esp[d.especialidad], d.especialidad))
        c.execute("INSERT INTO docente VALUES (?,?,?,?)", (d.id, d.nombre, ded[d.dedicacion], esp[d.especialidad]))
        for dia, hi, hf in d.franjas_disponibles:
            c.execute("INSERT INTO disponibilidad_docente(id_docente, dia, hora_inicio, hora_fin) VALUES (?,?,?,?)",
                      (d.id, DIAS.index(dia) + 1, hi, hf))
    tec = {t: i + 1 for i, t in enumerate(Tecnologia)}
    for t, i in tec.items():
        c.execute("INSERT INTO tecnologia VALUES (?,?)", (i, t.value))
    for a in aulas:
        c.execute("INSERT INTO aula VALUES (?,?,?,?)", (a.id, a.nombre, a.capacidad, int(a.accesibilidad)))
        for t in a.tecnologia:
            c.execute("INSERT INTO aula_tecnologia VALUES (?,?)", (a.id, tec[t]))
    c.execute("INSERT INTO propuesta(id_semestre,id_usuario,nombre,estado,creada_en) VALUES (?,1,'Prototipo','BORRADOR','2026-10-21 00:00:00')",
              (propuesta.semestre,))
    ofertas = {}
    for s in propuesta.sesiones:
        clave = (s.curso, s.grupo)
        if clave not in ofertas:
            c.execute("INSERT OR IGNORE INTO curso VALUES (?,?)", (s.curso, s.curso))
            c.execute("INSERT OR IGNORE INTO grupo VALUES (?)", (s.grupo,))
            c.execute("INSERT INTO oferta(id_semestre,id_curso,id_grupo,cupo_esperado) VALUES (?,?,?,?)",
                      (propuesta.semestre, s.curso, s.grupo, s.cupo_esperado))
            ofertas[clave] = c.lastrowid
            for t in s.tecnologia_requerida:
                c.execute("INSERT INTO oferta_tecnologia VALUES (?,?)", (ofertas[clave], tec[t]))
        # el esquema normalizado guarda cupo/tecnología por oferta; el prototipo los tenía por sesión
        c.execute("INSERT INTO sesion(id_propuesta,id_oferta,id_docente,id_aula,dia,hora_inicio,hora_fin) VALUES (1,?,?,?,?,?,?)",
                  (ofertas[clave], s.docente_id, s.aula_id, DIAS.index(s.dia) + 1, s.hora_inicio, s.hora_fin))
    con.commit()


def leer(con, id_propuesta=1):
    tec = {i: Tecnologia(v) for i, v in con.execute("SELECT id_tecnologia, nombre FROM tecnologia")}
    docentes, aulas, sesiones = [], [], []
    ded = {i: Dedicacion(n) for i, n in con.execute("SELECT id_dedicacion, nombre FROM dedicacion")}
    for did, nom, idd, esp in con.execute("SELECT d.id_docente,d.nombre,d.id_dedicacion,e.nombre FROM docente d LEFT JOIN especialidad e USING(id_especialidad) ORDER BY 1"):
        fr = [(DIAS[dia - 1], hi, hf) for dia, hi, hf in con.execute(
            "SELECT dia,hora_inicio,hora_fin FROM disponibilidad_docente WHERE id_docente=? ORDER BY id_disponibilidad", (did,))]
        docentes.append(Docente(did, nom, ded[idd], esp or "", fr))
    for aid, nom, cap, acc in con.execute("SELECT id_aula,nombre,capacidad,accesible FROM aula ORDER BY 1"):
        ts = {tec[i] for (i,) in con.execute("SELECT id_tecnologia FROM aula_tecnologia WHERE id_aula=?", (aid,))}
        aulas.append(Aula(aid, nom, cap, ts, bool(acc)))
    q = """SELECT s.id_sesion,o.id_curso,o.id_grupo,s.dia,s.hora_inicio,s.hora_fin,s.id_docente,s.id_aula,o.cupo_esperado,o.id_oferta
           FROM sesion s JOIN oferta o USING(id_oferta) WHERE s.id_propuesta=? ORDER BY s.id_sesion"""
    for sid, cur, gr, dia, hi, hf, did, aid, cupo, io in con.execute(q, (id_propuesta,)):
        ts = {tec[i] for (i,) in con.execute("SELECT id_tecnologia FROM oferta_tecnologia WHERE id_oferta=?", (io,))}
        sesiones.append(Sesion(f"S{sid:02d}", cur, gr, DIAS[dia - 1], hi, hf, did, aid, cupo, ts))
    return docentes, aulas, PropuestaHorario("2026-2", sesiones)
